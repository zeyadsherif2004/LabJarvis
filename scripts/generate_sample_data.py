"""Generate explicitly synthetic, development-only LabJarvis fixtures."""

from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH


ROOT = Path(__file__).resolve().parents[1]
PROTOCOL_DIR = ROOT / "sample_data" / "protocols"
PROTOCOL_PATH = PROTOCOL_DIR / "development-only-ethanol-protocol.docx"


def generate_protocol() -> Path:
    """Create the small protocol fixture used by fake-mode tests and demos."""

    PROTOCOL_DIR.mkdir(parents=True, exist_ok=True)
    document = Document()
    title = document.add_heading("Development-only synthetic protocol", level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    document.add_paragraph(
        "DEVELOPMENT-ONLY. This synthetic fixture tests LabJarvis software behavior. "
        "It is not a validated laboratory protocol and must not be used for real work."
    )
    document.add_heading("Preparation", level=1)
    document.add_paragraph("1. Add 10 mL ethanol to the demonstration vessel.")
    document.add_paragraph("2. Incubate the synthetic sample for 5 minutes.")
    document.add_paragraph("3. Warning: do not proceed until the demonstration cap is sealed.")

    properties = document.core_properties
    properties.title = "Development-only synthetic LabJarvis protocol"
    properties.subject = "Deterministic fake-mode fixture; not laboratory instructions"
    properties.author = "LabJarvis development tooling"
    properties.comments = "Generated by scripts/generate_sample_data.py"
    document.save(str(PROTOCOL_PATH))
    return PROTOCOL_PATH


if __name__ == "__main__":
    generated = generate_protocol()
    print(generated.relative_to(ROOT).as_posix())
